# kodi-rt: list pycryptodome's C modules for cross/cmake/pycryptodome from its setup.py (parsed with ast as data;
# nothing in the source tree is run). Writes cross/cmake/pycryptodome/modules.cmake:
#   PYCD_MODULES  "<subpackage>/<module>|<source>,...|<include dir>,..."  e.g. "Cipher/_raw_aes|src/AES.c|src/"
# Usage: python -I scripts/pycd-gen-modules.py <pycryptodome source dir> <out modules.cmake>
import ast, os, sys

src, out = sys.argv[1], sys.argv[2]
tree = ast.parse(open(os.path.join(src, 'setup.py'), encoding='utf-8').read())
mods = []
for node in ast.walk(tree):
    if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == 'ext_modules' for t in node.targets):
        for call in node.value.elts:
            name = ast.literal_eval(call.args[0])                  # e.g. Crypto.Cipher._raw_aes
            kw = {k.arg: ast.literal_eval(k.value) for k in call.keywords if k.arg in ('sources', 'include_dirs')}
            parts = name.split('.')
            assert parts[0] == 'Crypto' and len(parts) == 3, name
            incs = kw.get('include_dirs', [])
            for p in kw['sources'] + incs:
                assert os.path.exists(os.path.join(src, p)), p
            mods.append(f'{parts[1]}/{parts[2]}|{",".join(kw["sources"])}|{",".join(incs)}')
assert mods, 'no ext_modules found'
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('# Generated by scripts/pycd-gen-modules.py from pycryptodome 3.23.0 setup.py (ext_modules). Do not edit.\n')
    f.write('# <subpackage>/<module>|<sources>|<include dirs> (comma-separated); compiler_opt.py drops _raw_aesni and _ghash_clmul where\n')
    f.write('# the compiler has no AES-NI / CLMUL intrinsics (here: ARM32).\n')
    f.write('set(PYCD_MODULES\n' + ''.join(f'  "{m}"\n' for m in mods) + ')\n')
print(f'{out}: {len(mods)} modules')
