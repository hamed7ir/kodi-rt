#!/usr/bin/env python3
# kodi-rt Python stage: write cross/cmake/python3/sources.cmake from CPython's PCbuild project files, so the CMake
# build compiles exactly the files PCbuild compiles (platform ARM; the x64 reference build uses the same lists, which
# only drops the two AVX-only BLAKE2 files).
# Usage: python -I scripts/py-gen-sources.py <CPython source dir> <output sources.cmake>
import os, re, subprocess, sys

src, out = sys.argv[1], sys.argv[2]
here = os.path.dirname(os.path.abspath(__file__))
pcb = os.path.join(src, 'PCbuild')

def run(*args):
    r = subprocess.run([sys.executable, '-I', os.path.join(here, 'py-vcxproj.py'), *args],
                       capture_output=True, text=True, check=True)
    return [l for l in r.stdout.splitlines() if l.strip()]

def sources(proj):
    return run('sources', os.path.join(pcb, proj + '.vcxproj'), 'ARM')

# external source folders of PCbuild -> our CMake variables (or the in-tree copy)
MACROS = {
    '$(bz2Dir)': '${PY_BZ2_DIR}',
    '$(mpdecimalDir)': 'Modules/_decimal',      # CPython 3.14 still bundles libmpdec
}

def mapped(path):
    for k, v in MACROS.items():
        if path.startswith(k):
            return v + path[len(k):]
    return path

def cmake_list(name, items, note=''):
    lines = [f'# {note}' if note else None, f'set({name}']
    lines += [f'  {i}' for i in items]
    lines.append(')')
    return '\n'.join(l for l in lines if l is not None)

core = sources('pythoncore')
freeze = sources('_freeze_module')
frozen = run('frozen', os.path.join(pcb, '_freeze_module.vcxproj'))

# extension modules that the Kodi build compiles into python314.dll (name -> PCbuild project)
MODULES = ['_socket', 'select', '_ssl', '_hashlib', '_sqlite3', 'pyexpat', '_elementtree', '_bz2', '_lzma',
           'unicodedata', '_decimal', '_multiprocessing', '_overlapped', '_asyncio', '_queue', '_uuid',
           '_zoneinfo', 'winsound', '_ctypes', '_zstd']
parts = ['# Generated by scripts/py-gen-sources.py from CPython\'s PCbuild/*.vcxproj (platform ARM). Do not edit.',
         '# Paths are relative to PY_SRC unless they start with a ${...} variable.',
         cmake_list('PY_CORE_SOURCES', core, 'pythoncore.vcxproj -> python314.dll'),
         cmake_list('PY_FREEZE_SOURCES', freeze, '_freeze_module.vcxproj -> the host tool that freezes the modules')]
frozen_items = []
for line in frozen:
    mod, py, _ = line.split('\t')
    frozen_items.append(f'"{mod}|{py}"')
frozen_items.append('"getpath|Modules/getpath.py"')
parts.append(cmake_list('PY_FROZEN_MODULES', frozen_items, 'module|source; the headers go to <frozen dir>/Python/frozen_modules/<module>.h'))
for m in MODULES:
    items = []
    for p in sources(m):
        p = mapped(p)
        if '$(' in p:
            continue        # external library sources (e.g. zstd): the CMake build links the prefix's library
        items.append(p)
    parts.append(cmake_list(f'PY_MOD_{m}_SOURCES', items, f'{m}.vcxproj'))
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, 'w', newline='\n').write('\n\n'.join(parts) + '\n')
print(f'{out}: core {len(core)}, freeze {len(freeze)}, frozen {len(frozen_items)}, modules {len(MODULES)}')
