# kodi-rt: Pillow's C source lists for cross/cmake/pillow, from its setup.py (parsed with ast as data; nothing in the
# source tree is run). Writes cross/cmake/pillow/sources.cmake:
#   PIL_IMAGING_SOURCES  src/_imaging.c + src/<_IMAGING>.c + src/libImaging/<_LIB_IMAGING>.c   (PIL._imaging)
#   PIL_MODE_SOURCES     the pil_imaging_mode helper library (src/libImaging/Mode.c)
# Usage: python -I scripts/pil-gen-sources.py <pillow source dir> <out sources.cmake>
import ast, os, sys

src, out = sys.argv[1], sys.argv[2]
tree = ast.parse(open(os.path.join(src, 'setup.py'), encoding='utf-8').read())
vals = {}
for node in tree.body:
    if isinstance(node, (ast.Assign, ast.AnnAssign)):
        targets = node.targets if isinstance(node, ast.Assign) else [node.target]
        for t in targets:
            if isinstance(t, ast.Name) and t.id in ('_IMAGING', '_LIB_IMAGING', 'libraries'):
                vals[t.id] = ast.literal_eval(node.value)
imaging = ['src/_imaging.c'] + [f'src/{s}.c' for s in vals['_IMAGING']] + [f'src/libImaging/{s}.c' for s in vals['_LIB_IMAGING']]
mode = [s for name, info in vals['libraries'] if name == 'pil_imaging_mode' for s in info['sources']]
for p in imaging + mode:
    assert os.path.isfile(os.path.join(src, p)), p
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('# Generated by scripts/pil-gen-sources.py from Pillow 12.0.0 setup.py (_IMAGING, _LIB_IMAGING, libraries). Do not edit.\n')
    f.write('set(PIL_IMAGING_SOURCES\n' + ''.join(f'  {p}\n' for p in imaging) + ')\n')
    f.write('set(PIL_MODE_SOURCES\n' + ''.join(f'  {p}\n' for p in mode) + ')\n')
print(f'{out}: _imaging {len(imaging)} files, pil_imaging_mode {len(mode)}')
