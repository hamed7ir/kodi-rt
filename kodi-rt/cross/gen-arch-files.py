# kodi-rt: write the x64 and x86 cross files from one table, the counterparts of the ARM32 ones (arm32-rt24.cmake,
# meson-arm32.ini, arm32-msvc.rsp, arm32-link.rsp, cc-arm32.sh, windres-arm32.sh, autotools-arm32/clang-cl,
# openssl-arm32.conf). Toolchain: rt2.4 f6e5f8e0 (tc/rt24d-cr). MSVC 14.44, SDK 10.0.26100.0 headers AND libraries
# (the 19041 split is only for ARM32, whose import libraries end there). Static CRT (/MT) everywhere.
# Usage: python -I cross/gen-arch-files.py        (rewrites the files; they are generated, edit this instead)
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RT = 'F:/kodi-rt/tc/rt24d-cr/bin'
VC = 'D:/Program Files/vs22buildtools/VC/Tools/MSVC/14.44.35207'
SDK = 'D:/Windows Kits/10'
SDKV = '10.0.26100.0'
ARCHS = {
    #       triple                      lib   machine cmake proc  meson family cpu       windres  openssl base
    'x64': ('x86_64-pc-windows-msvc', 'x64', 'x64', 'AMD64', 'x86_64', 'x86_64', 'x86_64', 'VC-WIN64A'),
    'x86': ('i686-pc-windows-msvc',   'x86', 'x86', 'x86',   'x86',    'i686',   'i686',   'VC-WIN32'),
}


def write(rel, text, exe=False):
    p = os.path.join(HERE, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote', rel)


for a, (triple, lib, machine, proc, mfam, mcpu, wtarget, osslbase) in ARCHS.items():
    gen = f'Generated by cross/gen-arch-files.py; edit that, not this.'
    libpaths = [f'{VC}/lib/{lib}', f'{SDK}/Lib/{SDKV}/ucrt/{lib}', f'{SDK}/Lib/{SDKV}/um/{lib}']

    write(f'{a}-rt24.cmake', f'''# kodi-rt CMake toolchain: desktop Windows {a} ({triple}) with rt2.4 f6e5f8e0 (tc/rt24d-cr). {gen}
# The x86 twin of cross/arm32-rt24.cmake (see its comments): MSVC 14.44 pinned, SDK {SDKV} headers and {a} import
# libraries, static CRT (/MT), /EHsc for C++, RC include folders, find_* rooted in prefix/{a}.
set(CMAKE_SYSTEM_NAME Windows)
set(CMAKE_SYSTEM_PROCESSOR {proc})
set(CMAKE_SYSTEM_VERSION 10.0)

set(_RT "{RT}")
set(_VCTOOLS "{VC}")
set(_WINSDK "{SDK}")
set(_SDKINC "{SDKV}")
set(_SDKLIB "{SDKV}")

set(CMAKE_C_COMPILER   "${{_RT}}/clang-cl.exe")
set(CMAKE_CXX_COMPILER "${{_RT}}/clang-cl.exe")
set(CMAKE_ASM_COMPILER "${{_RT}}/clang.exe")
set(CMAKE_AR           "${{_RT}}/llvm-lib.exe")
set(CMAKE_LINKER       "${{_RT}}/lld-link.exe")
set(CMAKE_RC_COMPILER  "${{_RT}}/llvm-rc.exe")
set(CMAKE_MT           "${{_RT}}/llvm-mt.exe")

set(_PIN "--target={triple} -vctoolsdir \\"${{_VCTOOLS}}\\" -winsdkdir \\"${{_WINSDK}}\\" -winsdkversion ${{_SDKINC}}")
set(CMAKE_C_FLAGS_INIT   "${{_PIN}}")
set(CMAKE_CXX_FLAGS_INIT "${{_PIN}} /EHsc")
set(CMAKE_ASM_FLAGS_INIT "--target={triple}")
set(CMAKE_RC_FLAGS_INIT "-I \\"${{_VCTOOLS}}/include\\" -I \\"${{_WINSDK}}/Include/${{_SDKINC}}/um\\" -I \\"${{_WINSDK}}/Include/${{_SDKINC}}/shared\\" -I \\"${{_WINSDK}}/Include/${{_SDKINC}}/ucrt\\"")

set(_LIBPATHS "/libpath:\\"${{_VCTOOLS}}/lib/{lib}\\" /libpath:\\"${{_WINSDK}}/Lib/${{_SDKLIB}}/ucrt/{lib}\\" /libpath:\\"${{_WINSDK}}/Lib/${{_SDKLIB}}/um/{lib}\\"")
set(CMAKE_EXE_LINKER_FLAGS_INIT    "${{_LIBPATHS}}")
set(CMAKE_SHARED_LINKER_FLAGS_INIT "${{_LIBPATHS}}")
set(CMAKE_MODULE_LINKER_FLAGS_INIT "${{_LIBPATHS}}")

set(CMAKE_MSVC_RUNTIME_LIBRARY "MultiThreaded")
cmake_policy(SET CMP0091 NEW)
# (CMP0091 NEW must also come from the command line: -DCMAKE_POLICY_DEFAULT_CMP0091=NEW, see arm32-rt24.cmake)

set(CMAKE_FIND_ROOT_PATH "F:/kodi-rt/prefix/{a}")
set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)
set(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_PACKAGE ONLY)
''')

    cc = ", ".join(repr(x) for x in [f'{RT}/clang-cl.exe', f'--target={triple}', '-vctoolsdir', VC, '-winsdkdir', SDK, '-winsdkversion', SDKV])
    la = ", ".join(repr('/libpath:' + p) for p in libpaths)
    write(f'meson-{a}.ini', f'''# kodi-rt meson cross file: desktop Windows {a} with rt2.4 f6e5f8e0 (clang-cl, lld-link, llvm-lib), /MT. {gen}
# As cross/meson-arm32.ini: meson's clang-cl detection runs a bare "lld-link" from PATH, so the caller puts
# {RT} first on PATH.
[binaries]
c = [{cc}]
cpp = [{cc}]
ar = '{RT}/llvm-lib.exe'
windres = '{RT}/llvm-rc.exe'
strip = '{RT}/llvm-strip.exe'
cmake = 'D:/Program Files/vs22buildtools/Common7/IDE/CommonExtensions/Microsoft/CMake/CMake/bin/cmake.exe'

[built-in options]
c_link_args = [{la}]
cpp_link_args = [{la}]
b_vscrt = 'mt'

[host_machine]
system = 'windows'
cpu_family = '{mfam}'
cpu = '{mcpu}'
endian = 'little'
''')

    write(f'{a}-target-msvc.rsp', f'''--target={triple}
-vctoolsdir "{VC}"
-winsdkdir "{SDK}"
-winsdkversion {SDKV}
''')
    write(f'{a}-target-link.rsp', f'-machine:{machine}\n' + ''.join(f'-libpath:"{p}"\n' for p in libpaths))

    write(f'cc-{a}.sh', f'''#!/bin/sh
# kodi-rt: TARGET C compiler for FFmpeg's configure, desktop Windows {a}: clang-cl rt2.4 f6e5f8e0, MSVC ABI, /MT,
# SDK {SDKV}. {gen} (Never pass the rsp via --extra-cflags: configure feeds those to the assembler too.)
exec "{RT}/clang-cl.exe" "@F:/kodi-rt/cross/{a}-target-msvc.rsp" -MT "$@"
''')
    write(f'windres-{a}.sh', f'''#!/bin/sh
# kodi-rt: resource compiler for desktop Windows {a}, SDK {SDKV} headers. {gen}
M="{VC}"
S="{SDK}/Include/{SDKV}"
exec "{RT}/llvm-windres.exe" \\
  --target={wtarget} \\
  --preprocessor-arg=--target={triple} \\
  "--preprocessor-arg=-I$M/include" \\
  "--preprocessor-arg=-I$S/ucrt" \\
  "--preprocessor-arg=-I$S/um" \\
  "--preprocessor-arg=-I$S/shared" \\
  "$@"
''')

    lp = '\n'.join(f'  LP{i + 1}="-libpath:{p}"' for i, p in enumerate(libpaths))
    write(f'autotools-{a}/clang-cl', f'''#!/bin/sh
# kodi-rt: clang-cl for autotools builds (libiconv, ...), desktop Windows {a}, rt2.4 f6e5f8e0. {gen}
# As cross/autotools-arm32/clang-cl (see its comments): named "clang-cl" for automake's build-aux/compile; compile
# flags from cross/{a}-target-msvc.rsp; when it links, lld-link gets -machine:{machine} and the {a} library paths.
link=1; haslink=0
for a in "$@"; do
  case $a in
    -c|/c|-E|/E|-EP|/EP|-P|/P) link=0 ;;
    -link|/link|-LINK|/LINK) haslink=1 ;;
  esac
done
if [ $link = 1 ]; then
  export MSYS2_ARG_CONV_EXCL="/link;-libpath:"
{lp}
  if [ $haslink = 1 ]; then
    exec "{RT}/clang-cl.exe" "@F:/kodi-rt/cross/{a}-target-msvc.rsp" -fuse-ld=lld "$@" -machine:{machine} "$LP1" "$LP2" "$LP3"
  else
    exec "{RT}/clang-cl.exe" "@F:/kodi-rt/cross/{a}-target-msvc.rsp" -fuse-ld=lld "$@" /link -machine:{machine} "$LP1" "$LP2" "$LP3"
  fi
fi
exec "{RT}/clang-cl.exe" "@F:/kodi-rt/cross/{a}-target-msvc.rsp" "$@"
''')

    write(f'openssl-{a}.conf', f'''## kodi-rt: an OpenSSL build target for desktop Windows {a}: OpenSSL's own {osslbase} with rt2.4 f6e5f8e0's
## clang-cl / lld-link / llvm-lib through kodi-rt's response files (SDK {SDKV}). {gen}
## Use with: perl Configure {osslbase}-kodirt --config=<this file> no-asm ...   (no-asm: OpenSSL's x86 assembly needs
## nasm, which is not on this server)
my %targets = (
    "{osslbase}-kodirt" => {{
        inherit_from    => [ "{osslbase}" ],
        CC              => "{RT}/clang-cl.exe",
        CFLAGS          => add('@F:/kodi-rt/cross/{a}-target-msvc.rsp'),
        LD              => "{RT}/lld-link.exe",
        LDFLAGS         => add('@F:/kodi-rt/cross/{a}-target-link.rsp'),
        AR              => "{RT}/llvm-lib.exe",
        RC              => "{RT}/llvm-rc.exe",
    }},
);
''')
